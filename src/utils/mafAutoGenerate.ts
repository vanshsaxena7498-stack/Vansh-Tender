import type { AttachmentItem, MafLineItem, MafTrackerRecord, Tender } from '../types/crm';
import { createMafItemId } from './mafCalculations.ts';

export interface ExtractedSpecItem {
  itemName: string;
  requiredQuantity: string;
}

export interface AutoMafMergeInput {
  tender: Tender;
  extractedDepartment: string;
  extractedItems: ExtractedSpecItem[];
  existingTrackers: MafTrackerRecord[];
  nowIso?: string;
}

export interface AutoMafMergeResult {
  nextTrackers: MafTrackerRecord[];
  targetTracker: MafTrackerRecord | null;
  addedCount: number;
  departmentUpdated: boolean;
}

export function normalizeMafItemKey(name: string): string {
  return (name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function findTenderAttachmentSlot(
  attachments: AttachmentItem[] | undefined,
  slotNumber: 1 | 2,
): AttachmentItem | undefined {
  const list = attachments ?? [];
  if (list.length === 0) return undefined;

  if (slotNumber === 1) {
    const explicit1 = list.find((att) =>
      /\battachment\s*1\b|\bnit\b|tender\s*document/i.test(att.slotLabel || ''),
    );
    if (explicit1) return explicit1;
    // Only fall back to index 0 if index 0 isn't explicitly tagged as Attachment 2 or 3
    if (
      list[0] &&
      !/\battachment\s*[23]\b|\bboq\b|technical\s*spec/i.test(list[0].slotLabel || '')
    ) {
      return list[0];
    }
    return undefined;
  }

  const explicit2 = list.find((att) =>
    /\battachment\s*2\b|\bboq\b|technical\s*spec/i.test(att.slotLabel || ''),
  );
  if (explicit2) return explicit2;
  if (
    list[1] &&
    !/\battachment\s*[13]\b/i.test(list[1].slotLabel || '')
  ) {
    return list[1];
  }
  return undefined;
}

export function buildTenderAttachmentExtractionSignature(tender: Tender): string {
  const att1 = findTenderAttachmentSlot(tender.attachments, 1);
  const att2 = findTenderAttachmentSlot(tender.attachments, 2);
  const sig1 = att1 ? `${att1.id}:${att1.fileName}:${att1.fileSize}` : 'none';
  const sig2 = att2 ? `${att2.id}:${att2.fileName}:${att2.fileSize}` : 'none';
  return `${tender.id}|${sig1}|${sig2}`;
}

export function parsePlainTextSpecItems(rawText: string): ExtractedSpecItem[] {
  if (!rawText || !rawText.trim()) return [];
  const lines = rawText
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter(Boolean);

  const items: ExtractedSpecItem[] = [];
  const seenKeys = new Set<string>();

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    // Skip CSV / table header rows
    if (
      i === 0 &&
      /^(s\.?\s*no|sr\.?\s*no|item\s*(name|description)?|sl\.?\s*no|product)[,|;\t]/i.test(line)
    ) {
      continue;
    }

    let candidateName = '';
    let candidateQty = '';

    // Check CSV / pipe / tab separated format: e.g. "1, Rugged Laptop, 10 Nos" or "Tactical Radio, 25 Sets"
    if (line.includes(',') || line.includes('\t') || line.includes('|')) {
      const sep = line.includes('\t') ? '\t' : line.includes('|') ? '|' : ',';
      const cols = line.split(sep).map((c) => c.replace(/^["']|["']$/g, '').trim());
      const nonEmpty = cols.filter(Boolean);
      if (nonEmpty.length >= 2 && /^\d+\.?$/.test(nonEmpty[0])) {
        candidateName = nonEmpty[1] || '';
        candidateQty = nonEmpty[2] || '';
      } else if (nonEmpty.length >= 1) {
        candidateName = nonEmpty[0] || '';
        candidateQty = nonEmpty[1] || '';
      }
    } else {
      // Check numbered / bulleted lines: "1. Laser Rangefinder - 12 Nos" or "- Thermal Monocular (5 Units)"
      const cleaned = line
        .replace(/^(?:\d+[.)]\s*|[-*•]\s*)/, '')
        .trim();
      const dashQtyMatch = cleaned.match(
        /^(.*?)\s*(?:[-–—:]|\bQty\b[:\s]*)\s*(\d+\s*[A-Za-z.]*)$/i,
      );
      const parenQtyMatch = cleaned.match(/^(.*?)\s*\((\d+\s*[A-Za-z.]*)\)$/);
      if (dashQtyMatch && dashQtyMatch[1].trim()) {
        candidateName = dashQtyMatch[1].trim();
        candidateQty = dashQtyMatch[2].trim();
      } else if (parenQtyMatch && parenQtyMatch[1].trim()) {
        candidateName = parenQtyMatch[1].trim();
        candidateQty = parenQtyMatch[2].trim();
      } else {
        candidateName = cleaned;
      }
    }

    const trimmedName = candidateName.trim().slice(0, 220);
    const key = normalizeMafItemKey(trimmedName);
    if (!trimmedName || !key || seenKeys.has(key)) continue;
    // Skip non-product boilerplate lines
    if (/^(total|grand total|note:|notes:|terms|specification|boq)$/i.test(trimmedName)) {
      continue;
    }
    seenKeys.add(key);
    items.push({
      itemName: trimmedName,
      requiredQuantity: candidateQty.trim().slice(0, 60),
    });
  }

  return items.slice(0, 50);
}

export function buildAutoGeneratedMafLineItem(
  spec: ExtractedSpecItem,
  seedIndex = 0,
  nowIso = new Date().toISOString(),
): MafLineItem {
  return {
    itemId: createMafItemId(seedIndex),
    itemName: spec.itemName.trim().slice(0, 220),
    requiredQuantity: (spec.requiredQuantity || '').trim().slice(0, 60),
    // Explicitly blank for manual OEM & Company entry later
    oemName: '',
    companyName: '',
    concernedPersonName: '',
    contactNo: '',
    mailId: '',
    oemContact: '',
    mafStatus: 'Pending',
    mafRequestedDate: '',
    // Never copy tender attachments into MAF item attachments
    mafDocumentUrl: '',
    mafDocumentName: '',
    mafAttachmentId: undefined,
    remarks: '',
    updatedAt: nowIso,
  };
}

export function mergeAutoMafIntoTrackers(input: AutoMafMergeInput): AutoMafMergeResult {
  const {
    tender,
    extractedDepartment,
    extractedItems,
    existingTrackers,
    nowIso = new Date().toISOString(),
  } = input;

  const cleanExtractedDept = (extractedDepartment || '').trim().slice(0, 200);
  const resolvedDept = cleanExtractedDept || tender.department.trim().slice(0, 200) || 'Department';
  const normalizedTenderCode = tender.tenderId.trim().toLowerCase();

  const existingIndex = existingTrackers.findIndex(
    (t) =>
      (t.tenderRefId && t.tenderRefId === tender.id) ||
      (normalizedTenderCode && t.tenderId.trim().toLowerCase() === normalizedTenderCode),
  );

  // Deduplicate incoming extracted items by normalized key
  const dedupedSpecs: ExtractedSpecItem[] = [];
  const incomingSeen = new Set<string>();
  for (const rawSpec of extractedItems) {
    const cleanName = (rawSpec?.itemName || '').trim().slice(0, 220);
    const key = normalizeMafItemKey(cleanName);
    if (!cleanName || !key || incomingSeen.has(key)) continue;
    incomingSeen.add(key);
    dedupedSpecs.push({
      itemName: cleanName,
      requiredQuantity: (rawSpec?.requiredQuantity || '').trim().slice(0, 60),
    });
  }

  if (existingIndex === -1) {
    if (dedupedSpecs.length === 0) {
      return {
        nextTrackers: existingTrackers,
        targetTracker: null,
        addedCount: 0,
        departmentUpdated: false,
      };
    }

    const newItems = dedupedSpecs
      .slice(0, 50)
      .map((spec, idx) => buildAutoGeneratedMafLineItem(spec, idx, nowIso));

    const newTracker: MafTrackerRecord = {
      id: `maf-${tender.id}`,
      tenderRefId: tender.id,
      tenderId: tender.tenderId,
      tenderTitle: tender.title,
      department: resolvedDept,
      tenderDueDate: tender.submissionDueDate,
      itemsMAF: newItems,
      createdAt: nowIso,
      updatedAt: nowIso,
    };

    return {
      nextTrackers: [newTracker, ...existingTrackers],
      targetTracker: newTracker,
      addedCount: newItems.length,
      departmentUpdated: true,
    };
  }

  const existingTracker = existingTrackers[existingIndex];
  const existingKeys = new Set(
    (existingTracker.itemsMAF ?? []).map((it) => normalizeMafItemKey(it.itemName)),
  );

  const itemsToAppend: MafLineItem[] = [];
  const remainingSlots = Math.max(0, 50 - (existingTracker.itemsMAF?.length ?? 0));

  for (const spec of dedupedSpecs) {
    if (itemsToAppend.length >= remainingSlots) break;
    const key = normalizeMafItemKey(spec.itemName);
    if (existingKeys.has(key)) continue;
    existingKeys.add(key);
    itemsToAppend.push(
      buildAutoGeneratedMafLineItem(
        spec,
        (existingTracker.itemsMAF?.length ?? 0) + itemsToAppend.length,
        nowIso,
      ),
    );
  }

  const nextDepartment = cleanExtractedDept || existingTracker.department || resolvedDept;
  const departmentUpdated =
    Boolean(cleanExtractedDept) && cleanExtractedDept !== (existingTracker.department || '');

  const metadataChanged =
    existingTracker.tenderRefId !== tender.id ||
    existingTracker.tenderId !== tender.tenderId ||
    existingTracker.tenderTitle !== tender.title ||
    existingTracker.tenderDueDate !== tender.submissionDueDate ||
    departmentUpdated;

  if (itemsToAppend.length === 0 && !metadataChanged) {
    return {
      nextTrackers: existingTrackers,
      targetTracker: existingTracker,
      addedCount: 0,
      departmentUpdated: false,
    };
  }

  // Merge strictly appends newly discovered items without touching existing user-edited OEM rows
  const updatedTracker: MafTrackerRecord = {
    ...existingTracker,
    tenderRefId: tender.id,
    tenderId: tender.tenderId,
    tenderTitle: tender.title,
    department: nextDepartment,
    tenderDueDate: tender.submissionDueDate,
    itemsMAF: [...(existingTracker.itemsMAF ?? []), ...itemsToAppend].slice(0, 50),
    updatedAt: nowIso,
  };

  const nextTrackers = existingTrackers.map((t, idx) =>
    idx === existingIndex ? updatedTracker : t,
  );

  return {
    nextTrackers,
    targetTracker: updatedTracker,
    addedCount: itemsToAppend.length,
    departmentUpdated,
  };
}
