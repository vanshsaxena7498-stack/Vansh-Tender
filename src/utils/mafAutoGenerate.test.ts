function makeAtt(slotLabel: string, fileName: string, id = 'att-1'): AttachmentItem {
  return {
    id,
    slotLabel,
    fileName,
    fileType: 'application/pdf',
    fileSize: 12000,
    uploadedAt: '2026-11-01',
    dataUrl: 'data:application/pdf;base64,AAAA',
  };
}

test('findTenderAttachmentSlot matches Attachment 1 and Attachment 2 by slotLabel even when Attachment 1 is omitted', () => {
  const onlyAtt2 = [makeAtt('Attachment 2 · BOQ / Technical Spec', 'spec.pdf', 'att-2')];
  assert.equal(findTenderAttachmentSlot(onlyAtt2, 1), undefined);
  assert.equal(findTenderAttachmentSlot(onlyAtt2, 2)?.id, 'att-2');

  const both = [
    makeAtt('Attachment 1 · NIT / Tender Document', 'nit.pdf', 'att-1'),
    makeAtt('Attachment 2 · BOQ / Technical Spec', 'spec.pdf', 'att-2'),
  ];
  assert.equal(findTenderAttachmentSlot(both, 1)?.id, 'att-1');
  assert.equal(findTenderAttachmentSlot(both, 2)?.id, 'att-2');
});

