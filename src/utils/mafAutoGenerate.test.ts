test('mergeAutoMafIntoTrackers creates 5 individual MAF items with Attachment 1 department and is strictly idempotent on re-save', () => {
  const tender = makeTender();
  const fiveItems = [
    { itemName: 'Rugged Tactical Laptop', requiredQuantity: '10 Nos' },
    { itemName: 'Thermal Monocular', requiredQuantity: '5 Nos' },
    { itemName: 'Laser Rangefinder', requiredQuantity: '8 Nos' },
    { itemName: 'Tactical VHF Radio Set', requiredQuantity: '20 Nos' },
    { itemName: 'Portable Solar Charger 100W', requiredQuantity: '15 Nos' },
  ];

  // First save: generates 1 tracker with 5 individual Pending items
  const firstRun = mergeAutoMafIntoTrackers({
    tender,
    extractedDepartment: 'Directorate General of Infantry, Indian Army',
    extractedItems: fiveItems,
    existingTrackers: [],
    nowIso: '2026-11-18T10:00:00Z',
  });

  assert.equal(firstRun.addedCount, 5);
  assert.equal(firstRun.nextTrackers.length, 1);
  assert.equal(firstRun.targetTracker?.department, 'Directorate General of Infantry, Indian Army');
  assert.equal(firstRun.targetTracker?.itemsMAF.length, 5);
  for (const row of firstRun.targetTracker!.itemsMAF) {
    assert.equal(row.mafStatus, 'Pending');
    assert.equal(row.oemName, '');
    assert.equal(row.companyName, '');
    assert.equal(row.concernedPersonName, '');
    assert.equal(row.contactNo, '');
    assert.equal(row.mailId, '');
    assert.equal(row.mafDocumentUrl, '');
  }

  // User manually fills OEM + Company details on item 1
  const editedTrackers: MafTrackerRecord[] = firstRun.nextTrackers.map((tr) => ({
    ...tr,
    itemsMAF: tr.itemsMAF.map((it, idx) =>
      idx === 0
        ? {
            ...it,
            oemName: 'Panasonic',
            companyName: 'Panasonic India Pvt Ltd',
            concernedPersonName: 'Deepanshu Sir',
            contactNo: '+91 9811469796',
            mailId: 'deepanshu@in.panasonic.com',
            mafStatus: 'Under Approval',
          }
        : it,
    ),
  }));

  // Second save / re-save with case/punctuation variation + 1 genuinely new item
  const secondRun = mergeAutoMafIntoTrackers({
    tender,
    extractedDepartment: 'Directorate General of Infantry, Indian Army',
    extractedItems: [
      { itemName: '  rugged tactical-laptop ', requiredQuantity: '10 Nos' },
      { itemName: 'Thermal Monocular', requiredQuantity: '5 Nos' },
      { itemName: 'Night Vision Goggles Gen-3', requiredQuantity: '6 Nos' },
    ],
    existingTrackers: editedTrackers,
    nowIso: '2026-11-18T11:00:00Z',
  });

  assert.equal(secondRun.addedCount, 1);
  assert.equal(secondRun.nextTrackers.length, 1);
  assert.equal(secondRun.targetTracker?.itemsMAF.length, 6);
  // Existing user edits must NOT be overwritten
  const firstItemAfterResave = secondRun.targetTracker!.itemsMAF[0];
  assert.equal(firstItemAfterResave.oemName, 'Panasonic');
  assert.equal(firstItemAfterResave.companyName, 'Panasonic India Pvt Ltd');
  assert.equal(firstItemAfterResave.mafStatus, 'Under Approval');

  // Third run with exact same items -> 0 added, identical tracker state
  const thirdRun = mergeAutoMafIntoTrackers({
    tender,
    extractedDepartment: 'Directorate General of Infantry, Indian Army',
    extractedItems: fiveItems,
    existingTrackers: secondRun.nextTrackers,
    nowIso: '2026-11-18T12:00:00Z',
  });
  assert.equal(thirdRun.addedCount, 0);
  assert.equal(thirdRun.targetTracker?.itemsMAF.length, 6);
  assert.equal(normalizeMafItemKey('Rugged Tactical-Laptop!'), 'rugged tactical laptop');
});

test('parsePlainTextSpecItems parses CSV and numbered product lists reliably', () => {
  const csv = [
    'S.No,Item Name,Qty',
    '1,Rugged Tactical Laptop,10 Nos',
    '2,Thermal Monocular,5 Nos',
    '3,Laser Rangefinder,8 Nos',
  ].join('\n');
  const parsedCsv = parsePlainTextSpecItems(csv);
  assert.equal(parsedCsv.length, 3);
  assert.deepEqual(parsedCsv[0], { itemName: 'Rugged Tactical Laptop', requiredQuantity: '10 Nos' });
  assert.deepEqual(parsedCsv[2], { itemName: 'Laser Rangefinder', requiredQuantity: '8 Nos' });

  const bullets = [
    '1. Dome Camera 4MP - 25 Nos',
    '2. Core Network Switch (4 Nos)',
  ].join('\n');
  const parsedBullets = parsePlainTextSpecItems(bullets);
  assert.equal(parsedBullets.length, 2);
  assert.deepEqual(parsedBullets[0], { itemName: 'Dome Camera 4MP', requiredQuantity: '25 Nos' });
  assert.deepEqual(parsedBullets[1], { itemName: 'Core Network Switch', requiredQuantity: '4 Nos' });
});

test('evaluateTenderMafAttachmentGate waits until BOTH Attachment 1 (Bid Document) and Attachment 2 (Specification Document) exist', () => {
  const noAttachments = makeTender({ attachments: [] });
  assert.equal(evaluateTenderMafAttachmentGate(noAttachments).ready, false);

  const onlyAtt1 = makeTender({
    attachments: [makeAtt('Attachment 1 · NIT / Tender Document', 'bid.pdf', 'att-1')],
  });
  const resAtt1 = evaluateTenderMafAttachmentGate(onlyAtt1);
  assert.equal(resAtt1.ready, false);
  assert.equal(resAtt1.attachment1?.id, 'att-1');
  assert.equal(resAtt1.attachment2, undefined);

  const onlyAtt2 = makeTender({
    attachments: [makeAtt('Attachment 2 · BOQ / Technical Spec', 'spec.pdf', 'att-2')],
  });
  const resAtt2 = evaluateTenderMafAttachmentGate(onlyAtt2);
  assert.equal(resAtt2.ready, false);
  assert.equal(resAtt2.attachment1, undefined);
  assert.equal(resAtt2.attachment2?.id, 'att-2');

  const bothWithEmptyAtt2 = makeTender({
    attachments: [
      makeAtt('Attachment 1 · NIT / Tender Document', 'bid.pdf', 'att-1'),
      { ...makeAtt('Attachment 2 · BOQ / Technical Spec', 'spec.pdf', 'att-2'), dataUrl: '' },
    ],
  });
  assert.equal(evaluateTenderMafAttachmentGate(bothWithEmptyAtt2).ready, false);

  // Resolves cached dataUrl when stored externally (e.g., Firestore attachmentFiles map)
  const resResolved = evaluateTenderMafAttachmentGate(bothWithEmptyAtt2, (att) =>
    att.id === 'att-2' ? 'data:application/pdf;base64,BBBB' : att.dataUrl,
  );
  assert.equal(resResolved.ready, true);
  assert.equal(resResolved.attachment1?.id, 'att-1');
  assert.equal(resResolved.attachment2?.id, 'att-2');
});

